/** A snapshot of `files` in memory. `reads` lists every path that was read, in order. */
export function memorySnapshot(files: FixtureFiles = FILES, commit = COMMIT): RepositorySnapshot & { reads: string[] } {
  const bytesOf = (f: FixtureFile): Uint8Array | undefined => (typeof f === "string" ? Buffer.from(f) : f instanceof Uint8Array ? f : undefined);
  const entries: RepositoryEntry[] = Object.entries(files).map(([path, f]) => {
    const data = bytesOf(f);
    if (data) return { path, kind: "file", bytes: data.byteLength };
    return "link" in (f as object) ? { path, kind: "symlink", bytes: Buffer.byteLength((f as { link: string }).link) } : { path, kind: "submodule", bytes: 0 };
  });
  const reads: string[] = [];
  return {
    commit,
    entries,
    unlisted: 0,
    reads,
    read(path) {
      reads.push(path);
      const data = Object.hasOwn(files, path) ? bytesOf(files[path] as FixtureFile) : undefined;
      if (!data) throw new Error("not a file of the snapshot");
      return data;
    },
  };
}

